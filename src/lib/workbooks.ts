import "server-only";
import { randomBytes } from "node:crypto";
import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { WorkbookMapping } from "./mapping";
import { slugify } from "./parse";

export type WorkbookSource =
  | { type: "drive"; fileId: string }
  /** Uploaded through the Import page; `file` is a name inside the workbooks directory. */
  | { type: "upload"; file: string; originalName: string }
  /** Development copy configured with SHEET_FILE_PATH. */
  | { type: "local"; path: string };

export interface Workbook {
  id: string;
  name: string;
  source: WorkbookSource;
  createdAt: string | null;
  /** Configured through environment variables; can't be removed from the app. */
  builtIn: boolean;
}

/** Where uploads and the registry live. Must be persistent storage in production. */
export function workbooksDir(): string {
  return path.resolve(/*turbopackIgnore: true*/ process.cwd(), process.env.WORKBOOKS_DIR?.trim() || "data/workbooks");
}

const indexPath = () => path.join(workbooksDir(), "index.json");

export function uploadPath(file: string): string {
  // Stored names are generated by us, but never let one escape the directory.
  return path.join(workbooksDir(), path.basename(file));
}

function builtInWorkbook(): Workbook | null {
  const name = process.env.DEFAULT_WORKBOOK_NAME?.trim() || "Main sheet";
  const local = process.env.SHEET_FILE_PATH?.trim();
  const fileId = process.env.GOOGLE_DRIVE_FILE_ID?.trim();
  const source: WorkbookSource | null = local
    ? { type: "local", path: local }
    : fileId
      ? { type: "drive", fileId }
      : null;
  return source ? { id: "main", name, source, createdAt: null, builtIn: true } : null;
}

async function readIndex(): Promise<Workbook[]> {
  try {
    const parsed = JSON.parse(await readFile(indexPath(), "utf8")) as Workbook[];
    return parsed.map((w) => ({ ...w, builtIn: false }));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw err;
  }
}

/** Write-then-rename so a crash mid-write can't leave a half-written file. */
async function writeJson(file: string, value: unknown) {
  await mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, JSON.stringify(value, null, 2));
  await rename(tmp, file);
}

async function writeIndex(workbooks: Workbook[]) {
  await writeJson(indexPath(), workbooks);
}

/** Built-in workbook first (if configured), then imports, newest first. */
export async function listWorkbooks(): Promise<Workbook[]> {
  const builtIn = builtInWorkbook();
  const imported = (await readIndex()).sort((a, b) => (b.createdAt ?? "").localeCompare(a.createdAt ?? ""));
  return builtIn ? [builtIn, ...imported] : imported;
}

export function newWorkbookId(name: string): string {
  return `${slugify(name).slice(0, 40) || "sheet"}-${randomBytes(3).toString("hex")}`;
}

export async function addWorkbook(workbook: Omit<Workbook, "builtIn" | "createdAt">): Promise<Workbook> {
  const entry: Workbook = { ...workbook, builtIn: false, createdAt: new Date().toISOString() };
  await writeIndex([...(await readIndex()), entry]);
  return entry;
}

export async function removeWorkbook(id: string): Promise<void> {
  const all = await readIndex();
  const target = all.find((w) => w.id === id);
  if (!target) throw new Error("That workbook doesn't exist or can't be removed.");
  await writeIndex(all.filter((w) => w.id !== id));
  await setMapping(id, null);
  if (target.source.type === "upload") await rm(uploadPath(target.source.file), { force: true });
}

/** Pulls the file ID out of any Drive or Sheets link, or accepts a bare ID. */
export function parseDriveLink(input: string): string | null {
  const text = input.trim();
  if (/^[\w-]{20,}$/.test(text)) return text;
  try {
    const u = new URL(text);
    if (!/(^|\.)google\.com$/.test(u.hostname)) return null;
    return u.pathname.match(/\/d\/([\w-]{20,})/)?.[1] ?? u.searchParams.get("id");
  } catch {
    return null;
  }
}

/** Link to open the workbook in Google, when it lives in Drive. */
export function sheetUrl(workbook: Workbook): string | null {
  const fileId =
    workbook.source.type === "drive"
      ? workbook.source.fileId
      : workbook.builtIn
        ? process.env.GOOGLE_DRIVE_FILE_ID?.trim()
        : null;
  return fileId ? `https://docs.google.com/spreadsheets/d/${fileId}/edit` : null;
}

// ---- Column mappings, one per workbook (the built-in one included) ----

const mappingsPath = () => path.join(workbooksDir(), "mappings.json");

async function readMappings(): Promise<Record<string, WorkbookMapping>> {
  try {
    return JSON.parse(await readFile(mappingsPath(), "utf8"));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return {};
    throw err;
  }
}

/** The confirmed column mapping, or null when the workbook relies on auto-detection. */
export async function getMapping(id: string): Promise<WorkbookMapping | null> {
  return (await readMappings())[id] ?? null;
}

export async function setMapping(id: string, mapping: WorkbookMapping | null): Promise<void> {
  const all = await readMappings();
  if (mapping) all[id] = mapping;
  else if (id in all) delete all[id];
  else return;
  await writeJson(mappingsPath(), all);
}

// ---- Uploads waiting for the user to confirm their columns ----

const pendingDir = () => path.join(workbooksDir(), "pending");
const PENDING_NAME = /^[a-f0-9]{24}\.(xlsx|xlsm|xls|ods)$/;
const PENDING_TTL_MS = 24 * 60 * 60 * 1000;

/** Stores an upload until it's confirmed; returns the name to confirm it with. Clears stale ones. */
export async function savePending(bytes: Uint8Array, ext: string): Promise<string> {
  await mkdir(pendingDir(), { recursive: true });
  const now = Date.now();
  for (const name of await readdir(pendingDir())) {
    const file = path.join(pendingDir(), name);
    const info = await stat(file).catch(() => null);
    if (info && now - info.mtimeMs > PENDING_TTL_MS) await rm(file, { force: true });
  }
  const name = `${randomBytes(12).toString("hex")}${ext.toLowerCase()}`;
  await writeFile(path.join(pendingDir(), name), bytes);
  return name;
}

export async function readPending(name: string): Promise<Uint8Array | null> {
  if (!PENDING_NAME.test(name)) return null;
  try {
    return new Uint8Array(await readFile(path.join(pendingDir(), name)));
  } catch {
    return null;
  }
}

/** Moves a confirmed upload to its permanent name inside the workbooks directory. */
export async function promotePending(name: string, file: string): Promise<void> {
  if (!PENDING_NAME.test(name)) throw new Error("That upload has expired. Please upload the file again.");
  await rename(path.join(pendingDir(), name), uploadPath(file));
}
